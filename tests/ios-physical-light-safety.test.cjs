const read=p=>fs.readFileSync(path.join(root,p),'utf8');

test('dynamic playback requires persisted first-use consent',()=>{
  const model=read('ios/App/AppModel.swift');
  const safety=read('ios/App/AppModel+Safety.swift');
  const bridge=read('ios/App/AppModel+BridgePlayback.swift');
  const live=read('ios/App/AppModel+Live.swift');
  const rootView=read('ios/App/Views/RootView.swift');
  assert.match(model,/pendingDynamicAction/);
  assert.match(safety,/try PhysicalLightSafetyStore\.saveSynchronously\(updated, defaults: setupDefaults\)\s+safetySettings = updated/);
  const store=read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/PhysicalLightSafetyStore.swift');
  assert.match(store,/payloadSHA256/);
  assert.match(store,/quarantine/);
  assert.match(bridge,/requiresDynamicLightConsent/);
  assert.match(live,/requiresDynamicLightConsent/);
  assert.match(rootView,/Dynamic light safety/);
  assert.match(rootView,/stop immediately if you feel discomfort/);
});

test('Reduce Light Motion bounds engine behavior and keeps emergency controls available',()=>{
  const policy=read('ios/Packages/HueBoardKit/Sources/HueBoardKit/PhysicalLightSafety.swift');
  const runner=read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/NativeLiveRunner.swift');
  const settings=read('ios/App/Views/SettingsView.swift');
  const lights=read('ios/App/Views/LightsView.swift');
  const banner=read('ios/App/Views/Components.swift');
  assert.match(policy,/speed = min\(result\.speed, 0\.55\)/);
  assert.match(policy,/energy = min\(result\.energy, 45\)/);
  assert.match(policy,/return max\(8_000, count \* 800\)/);
  const planner=read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/StudioFramePlanner.swift');
  assert.match(runner,/try await planner\.frame\(/);
  assert.match(planner,/adjustedEngineSettings/);
  assert.match(planner,/sampleTime \* patternSpeed/);
  assert.match(planner,/placement\.role\.isStatic \? 0 : cueTime/);
  assert.match(planner,/selectedCue\?\.settings \?\? requestedSettings/);
  assert.match(read('ios/App/AppModel+BridgePlayback.swift'),/outputLimits: preservedOutputCeilings\(\)/);
  assert.match(read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/BridgeSceneTransport.swift'),/outputLimits: outputLimits/);
  assert.doesNotMatch(read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/BridgeSceneTransport.swift'),/outputLimits: \[:\]/);
  assert.match(settings,/Reduce Light Motion/);
  assert.match(settings,/not a medical guarantee/);
  assert.match(lights,/Turn off now/);
  assert.match(banner,/Button\("Turn off now"/);
  assert.match(banner,/case \.idle, \.failed:"Recovery"/);
  const everyday=lights.slice(lights.indexOf('Everyday control'), lights.indexOf('Brightness'));
  const powerRow=everyday.slice(0, everyday.indexOf('.disabled(!model.canUseEverydayControls)'));
  assert.doesNotMatch(powerRow,/Turn off now/);
  assert.doesNotMatch(banner,/HueEngine\.sample/);
  const scenes=read('ios/Packages/HueBoardKit/Sources/HueBoardKit/SceneBuilder.swift');
  const transport=read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/BridgeSceneTransport.swift');
  const playback=read('ios/App/AppModel+BridgePlayback.swift');
  const ambient=read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/HueLightFrameTransports.swift');
  assert.match(scenes,/if reduceLightMotion \{ speed = min\(speed, 0\.25\) \}/);
  assert.match(playback,/reduceLightMotion: effectiveSafetySettings\.reduceLightMotion/);
  assert.match(transport,/reduceLightMotion: reduceLightMotion/);
  const rest=ambient.slice(ambient.indexOf('actor RestAmbientTransport'));
  assert.match(rest,/duration >= 4_500/);
  const app=read('ios/App/AppModel.swift');
  assert.match(app,/func presentConnection\(\)/);
  assert.match(app,/var canTurnOffNow: Bool \{ isReady && !foreignRecoveryPending && !emergencyOffInFlight \}/);
  assert.match(app,/var canUseEverydayControls: Bool \{\s*isReady && setupStorageIssue == nil && !requiresRecovery && playback\.snapshot\.mode != \.bridge/);
  assert.doesNotMatch(app,/canUseEverydayControls: Bool \{\n    isReady && !hasRestorePoint/);
  const recovery=read('ios/App/AppModel+Recovery.swift');
  assert.match(recovery,/foreignRecoveryPending = true/);
  assert.match(recovery,/Reconnect that Bridge and restore it before changing lights/);
  const live=read('ios/App/AppModel+Live.swift');
  const restore=live.slice(live.indexOf('func stopAndRestore()'));
  assert.match(restore,/Saved restore state belongs to a different Bridge/);
  assert.match(banner,/!model\.foreignRecoveryPending\s*&&\s*\(model\.hasRestorePoint/);
  assert.match(banner,/Button\("Stop & restore"\)[\s\S]*?\.disabled\(!model\.canStopAndRestore\)/);
  assert.match(recovery,/var canStopAndRestore: Bool \{\s*isReady && !isBusy && !emergencyOffInFlight && !foreignRecoveryPending/);
  assert.match(restore,/guard canStopAndRestore, let profile, let credential/);
  assert.match(read('ios/App/Views/LightsView.swift'),/another Bridge is still pending/);
  assert.match(read('ios/App/Views/LiveView.swift'),/effectiveDynamicBrightness/);
  assert.match(read('ios/App/Views/LiveView.swift'),/maximumDynamicBrightness/);
  assert.match(read('ios/App/Views/ScenesView.swift'),/discard that baseline from Settings/);
  assert.match(restore,/journal\.restoreAcceptedAt = nil\s+guard try await persistence\.replaceRestoreJournal\(journal, matching: reviewed\)[\s\S]*?playbackCoordinator\.submit\(/);
  assert.match(restore,/if failures == 0, skipped == 0 \{\s*var accepted = journal\s*accepted\.restoreAcceptedAt = Date\(\)/);
  assert.doesNotMatch(restore,/saveRestoreJournal\(nil\)/);
  assert.match(recovery,/Bridge readback matches the saved baseline/);
  assert.match(read('ios/Packages/HueBoardKit/Sources/HueBoardKit/Models.swift'),/self\.minimumBrightness=min\(max\(minimumBrightness,0\.1\),100\)/);
  assert.match(read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/PhysicalLightSafetyStore.swift'),/withRecoveredSettings\(defaults: defaults\)[\s\S]*?let safe = try Self\.encoded\(\.failedClosed\)\s+defaults\.set\(data, forKey: Key\.quarantine\)\s+defaults\.set\(safe, forKey: Key\.settings\)/);
  assert.match(read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/HueLightFrameTransports.swift'),/waitForInFlightWrites/);
  assert.match(read('ios/Packages/HueBoardKit/Sources/HueBoardKit/PhysicalLightSafety.swift'),/static let failedClosed/);
  assert.match(read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/PhysicalLightSafetyStore.swift'),/return \.failedClosed/);
  assert.match(read('ios/Packages/HueBoardKit/Sources/HueBoardKit/HueAPI.swift'),/minimumBrightness:reportedMinimum/);
  assert.match(read('ios/App/Views/SettingsView.swift'),/model\.presentConnection\(\)/);
  const journal=read('ios/Packages/HueBoardKit/Sources/HueBoardNativeCore/AppPersistence.swift');
  const loader=journal.slice(journal.indexOf('func loadRestoreJournal'), journal.indexOf('func saveRestoreJournal'));
  assert.ok(loader.indexOf('readRecoveryEnvelope')<loader.indexOf('loadState'));
  assert.doesNotMatch(read('ios/Packages/HueBoardKit/Sources/HueBoardKit/HueEvents.swift'),/payload\.prefix\(160\)/);
});

