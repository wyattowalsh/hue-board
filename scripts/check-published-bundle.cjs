'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const manifest=require('../releases/v'+require('../package.json').version+'.json');
const installer=fs.readFileSync(path.join(root,'install/install-hue-board.js'),'utf8');
const bytes=fs.readFileSync(path.join(root,manifest.artifact));
const digest=crypto.createHash('sha256').update(bytes).digest('hex');
assert.match(manifest.sourceRevision,/^[a-f0-9]{40}$/);
assert.match(manifest.sha256,/^[a-f0-9]{64}$/);
assert.equal(manifest.version,require('../package.json').version);
assert.ok(installer.includes(`const REVISION = '${manifest.sourceRevision}';`),'Installer commit disagrees with release manifest');
assert.ok(installer.includes(`const EXPECTED_SHA256 = '${manifest.sha256}';`),'Installer digest disagrees with release manifest');
assert.equal(digest,manifest.sha256,'Checked-in released bundle does not match the immutable published artifact');
console.log(`Verified published Hue Board ${manifest.version} bundle: ${digest}`);
