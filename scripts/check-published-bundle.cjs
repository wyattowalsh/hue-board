'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const installer=fs.readFileSync(path.join(root,'install/install-hue-board.js'),'utf8');
const extract=pattern=>{const value=installer.match(pattern)?.[1];assert.ok(value,'Missing installer release constant');return value;};
const version=extract(/const VERSION = '([^']+)'/);
const revision=extract(/const REVISION = '([a-f0-9]{40})'/);
const expectedDigest=extract(/const EXPECTED_SHA256 = '([a-f0-9]{64})'/);
const manifestPath=path.join(root,`releases/v${version}.json`);
assert.ok(fs.existsSync(manifestPath),`Missing release manifest for installed version ${version}`);
const manifest=JSON.parse(fs.readFileSync(manifestPath,'utf8'));
const artifactPath=path.join(root,manifest.artifact);
const bytes=fs.readFileSync(artifactPath);
const digest=crypto.createHash('sha256').update(bytes).digest('hex');
assert.equal(manifest.version,version,'Installer version disagrees with release manifest');
assert.equal(manifest.sourceRevision,revision,'Installer commit disagrees with release manifest');
assert.equal(manifest.sha256,expectedDigest,'Installer digest disagrees with release manifest');
assert.equal(manifest.artifact,'dist/hue-board.js');
assert.ok(bytes.toString('utf8').startsWith(`// Hue Board ${version} | Standalone Scriptable controller`),'Published bundle banner disagrees with installer version');
assert.equal(digest,manifest.sha256,'Checked-in published bundle does not match the immutable release digest');
console.log(`Verified published Hue Board ${version} bundle: ${digest}`);
